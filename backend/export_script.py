from datetime import datetime


def _step_lines(entry: dict):
    """Returns the pandas lines for one logged action, or None if that action changes nothing."""
    action = entry.get("action")
    col = entry.get("column")
    c = repr(col)

    if action == "fill_median":
        return [f"df[{c}] = df[{c}].fillna(df[{c}].median())"]

    if action == "fill_mode":
        return [f"df[{c}] = df[{c}].fillna(df[{c}].mode()[0])"]

    if action == "drop_duplicates":
        return ["df = df.drop_duplicates()"]

    if action == "cap_outliers":
        return [
            f"q1, q3 = df[{c}].quantile(0.25), df[{c}].quantile(0.75)",
            "iqr = q3 - q1",
            f"df[{c}] = df[{c}].clip(lower=q1 - 1.5 * iqr, upper=q3 + 1.5 * iqr)",
        ]

    if action == "standardize_text":
        return [
            f"mask = df[{c}].notna()",
            f"df.loc[mask, {c}] = df.loc[mask, {c}].astype(str).str.strip().str.title()",
        ]

    if action == "parse_dates":
        return [f'df[{c}] = pd.to_datetime(df[{c}], errors="coerce", format="mixed")']

    if action in ("blank_invalid_emails", "drop_invalid_emails"):
        lines = [f"invalid = df[{c}].notna() & ~df[{c}].astype(str).str.match(EMAIL_PATTERN)"]
        lines.append(f"df.loc[invalid, {c}] = None" if action.startswith("blank") else "df = df[~invalid]")
        return lines

    if action in ("blank_future_dates", "drop_future_dates"):
        lines = [f'future = pd.to_datetime(df[{c}], errors="coerce", format="mixed") > pd.Timestamp.now()']
        lines.append(f"df.loc[future, {c}] = None" if action.startswith("blank") else "df = df[~future]")
        return lines

    if action == "manual_correction":
        changes = entry.get("changes") or []
        if not changes:
            return [f"# (the individual edits to {c} were not recorded, so they cannot be replayed)"]
        pairs = [(int(ch["row_id"]), ch["value"]) for ch in changes]
        return [f"for row_id, value in {pairs!r}:", f"    set_value(df, row_id, {c}, value)"]

    if action in ("review_outliers", "review_future_dates", "review_invalid_emails"):
        return None  # these only flagged values for review and never changed the data

    return [f"# (skipped: '{action}' is not supported in exported code)"]


def build_script(source: dict | None, log: list, na_values: list) -> str:
    source = source or {}
    filename = source.get("filename") or "your_data.csv"
    is_excel = source.get("kind") == "excel"
    sheet = source.get("sheet")
    sheet_value = repr(sheet) if sheet else "0"

    # Only the steps after the last "reset to original" still apply to the current dataset
    start = 0
    for i, entry in enumerate(log):
        if entry.get("action") == "reset_to_original":
            start = i + 1
    steps = log[start:]

    body, count = [], 0
    for entry in steps:
        lines = _step_lines(entry)
        if lines is None:
            continue
        count += 1
        message = " ".join(str(entry.get("message") or entry.get("action") or "").split())
        stamp = entry.get("timestamp", "")
        body.append(f"    # Step {count} ({stamp}): {message}")
        body.extend("    " + line for line in lines)
        body.append("")

    if not body:
        body = ["    # No cleaning steps were applied in InsightForge, so the data is returned unchanged.", ""]

    if is_excel:
        loader = f"    df = pd.read_excel(path, sheet_name={sheet_value}, na_values=NA_VALUES, keep_default_na=True)"
        requirements = "pandas and openpyxl"
    else:
        loader = "    df = pd.read_csv(path, na_values=NA_VALUES, keep_default_na=True)"
        requirements = "pandas"

    header = [
        "# Cleaning script generated by InsightForge",
        f"# Generated on: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        f"# Source file: {filename}",
        f"# Cleaning steps replayed: {count}",
        "#",
        "# This script repeats, in the same order, every cleaning action applied in the app.",
        "# Usage:  python insightforge_cleaning.py [path/to/your_file]",
        f"# Requires: pip install {requirements.replace(' and ', ' ')}",
        "",
        "import sys",
        "",
        "import pandas as pd",
        "",
        f"SOURCE_FILE = {filename!r}",
        'OUTPUT_FILE = "cleaned_data.csv"',
        f"NA_VALUES = {na_values!r}  # text treated as missing, same as in the app",
        'EMAIL_PATTERN = r"^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$"',
        "",
        "",
        "def set_value(df, row_id, column, value):",
        "    # Used to replay values that were corrected by hand in the app",
        "    if pd.api.types.is_datetime64_any_dtype(df[column]):",
        "        value = pd.to_datetime(value)",
        "    df.loc[row_id, column] = value",
        "",
        "",
        "def load(path):",
        loader,
        "    df.columns = df.columns.astype(str).str.strip()",
        "    return df",
        "",
        "",
        "def clean(df):",
    ]

    footer = [
        "    return df",
        "",
        "",
        'if __name__ == "__main__":',
        "    path = sys.argv[1] if len(sys.argv) > 1 else SOURCE_FILE",
        "    data = load(path)",
        '    print(f"Loaded {len(data)} rows and {len(data.columns)} columns from {path}")',
        "    data = clean(data)",
        "    data.to_csv(OUTPUT_FILE, index=False)",
        '    print(f"Saved {len(data)} cleaned rows to {OUTPUT_FILE}")',
        "",
    ]

    return "\n".join(header + body + footer)